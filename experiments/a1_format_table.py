"""
Format A1 results into a publication-ready Table 1 with significance markers.

Conventions used here:
  ‡ : Bonferroni-corrected significant (p < 0.05/21 = 0.00238) vs ColBERT
  † : uncorrected significant (p < 0.05) vs ColBERT
  ⋆ : Bonferroni-corrected significant vs SBR  (only marked on IPSsimRF)
  *  : uncorrected significant vs SBR (only marked on IPSsimRF)

Two markers can stack: e.g. 0.6824‡⋆ means IPSsimRF beats both ColBERT and SBR
under Bonferroni correction.

Both t-test and bootstrap p-values are checked; the test used for the marker
is the *more conservative* of the two (i.e. higher p-value), so the markers
are robust to test choice.
"""
import os
import pandas as pd

OUT_DIR = "/mnt/primary/cikm 2026/experiments"
SIG_PATH = os.path.join(OUT_DIR, "a1_significance_results.csv")
PERQ_PATH = os.path.join(OUT_DIR, "a1_per_query_ndcg.csv")
TABLE_PATH = os.path.join(OUT_DIR, "a1_table1_with_significance.txt")
LATEX_PATH = os.path.join(OUT_DIR, "a1_table1_with_significance.tex")

CUTOFFS = [1, 3, 5, 10, 30, 50, 100]
N_TESTS = 21
BONF_ALPHA = 0.05 / N_TESTS
ALPHA_UNCORR = 0.05


def conservative_p(row):
    """Return the more conservative (higher) of t-test and bootstrap p-values."""
    return max(row["t_pvalue"], row["bootstrap_pvalue"])


def make_marker(sig_df, system, cutoff):
    """Compose significance markers for `system` at `cutoff`.
    Markers vs ColBERT (‡/†) are appended for SBR and IPSsimRF.
    Markers vs SBR (⋆/*) are appended only for IPSsimRF.
    System better than baseline means delta_a_minus_b for "Baseline vs system" is negative.
    """
    marker = ""
    if system == "ColBERT":
        return marker

    # vs ColBERT
    rec = sig_df[(sig_df["cutoff"] == cutoff) &
                 (sig_df["comparison"] == f"ColBERT vs {system}")]
    if len(rec) == 1:
        p = conservative_p(rec.iloc[0])
        delta = rec.iloc[0]["delta_a_minus_b"]
        better = delta < 0  # system better than ColBERT
        if better:
            if p < BONF_ALPHA:
                marker += "‡"   # ‡
            elif p < ALPHA_UNCORR:
                marker += "†"   # †

    # vs SBR (only for IPSsimRF)
    if system == "IPSsimRF":
        rec = sig_df[(sig_df["cutoff"] == cutoff) &
                     (sig_df["comparison"] == "SBR vs IPSsimRF")]
        if len(rec) == 1:
            p = conservative_p(rec.iloc[0])
            delta = rec.iloc[0]["delta_a_minus_b"]
            better = delta < 0  # IPSsimRF better than SBR
            if better:
                if p < BONF_ALPHA:
                    marker += "⋆"   # ⋆
                elif p < ALPHA_UNCORR:
                    marker += "*"

    return marker


def main():
    sig_df = pd.read_csv(SIG_PATH)
    perq_df = pd.read_csv(PERQ_PATH)

    means = perq_df.groupby(["system", "cutoff"])["ndcg"].mean().unstack("cutoff")
    means = means.loc[["ColBERT", "SBR", "IPSsimRF"], CUTOFFS]

    # Build formatted table (text)
    lines = []
    lines.append(f"Bonferroni alpha = {ALPHA_UNCORR}/{N_TESTS} = {BONF_ALPHA:.5f}")
    lines.append("Markers (significance against weaker system):")
    lines.append("  ‡ = Bonferroni-significant vs ColBERT")
    lines.append("  † = uncorrected (p<0.05) vs ColBERT")
    lines.append("  ⋆ = Bonferroni-significant vs SBR (IPSsimRF only)")
    lines.append("  * = uncorrected (p<0.05) vs SBR (IPSsimRF only)")
    lines.append("Conservative test (max of t-test and bootstrap p-value).")
    lines.append("")
    header = ["System"] + [f"nDCG@{k}" for k in CUTOFFS]
    rows = []
    for system in ["ColBERT", "SBR", "IPSsimRF"]:
        row = [system]
        for k in CUTOFFS:
            val = means.loc[system, k]
            marker = make_marker(sig_df, system, k)
            row.append(f"{val:.4f}{marker}")
        rows.append(row)

    # Print as fixed-width text table
    col_widths = [max(len(str(r[i])) for r in [header] + rows) for i in range(len(header))]
    sep = "  ".join("-" * w for w in col_widths)
    fmt_row = lambda r: "  ".join(s.ljust(w) for s, w in zip(r, col_widths))
    lines.append(fmt_row(header))
    lines.append(sep)
    for r in rows:
        lines.append(fmt_row(r))

    table_text = "\n".join(lines)
    with open(TABLE_PATH, "w") as f:
        f.write(table_text + "\n")
    print(table_text)
    print(f"\nSaved: {TABLE_PATH}")

    # ----- LaTeX version -----
    latex_lines = [
        "% Auto-generated by a1_format_table.py",
        "% Markers: ‡=Bonferroni vs ColBERT, †=uncorrected vs ColBERT,",
        "%          ⋆=Bonferroni vs SBR, *=uncorrected vs SBR (IPSsimRF only)",
        r"\begin{table}[t]",
        r"  \centering",
        r"  \caption{nDCG of ColBERT, SBR, and IPSsimRF on 53 TREC DL 2021 queries. "
        r"Significance markers indicate paired tests (more conservative of paired $t$-test and paired bootstrap, $B=10{,}000$) "
        r"under Bonferroni correction across 21 tests. "
        r"$\ddagger$=Bonferroni-significant vs ColBERT ($p<0.00238$); "
        r"$\dagger$=uncorrected vs ColBERT ($p<0.05$); "
        r"$\star$=Bonferroni-significant vs SBR; "
        r"$*$=uncorrected vs SBR.}",
        r"  \label{tab:relevance_feedback_results}",
        r"  \begin{tabular}{l" + "c" * len(CUTOFFS) + "}",
        r"    \toprule",
        "    System & " + " & ".join(f"nDCG@{k}" for k in CUTOFFS) + r" \\",
        r"    \midrule",
    ]
    # LaTeX marker translation
    def to_latex(s):
        return (s.replace("‡", r"$^\ddagger$")
                 .replace("†", r"$^\dagger$")
                 .replace("⋆", r"$^\star$")
                 .replace("*", r"$^*$"))

    for system in ["ColBERT", "SBR", "IPSsimRF"]:
        cells = []
        for k in CUTOFFS:
            val = means.loc[system, k]
            marker = make_marker(sig_df, system, k)
            cells.append(to_latex(f"{val:.4f}{marker}"))
        # Bold the best in each column
        latex_lines.append("    " + system + " & " + " & ".join(cells) + r" \\")

    latex_lines += [
        r"    \bottomrule",
        r"  \end{tabular}",
        r"\end{table}",
    ]
    with open(LATEX_PATH, "w") as f:
        f.write("\n".join(latex_lines) + "\n")
    print(f"Saved LaTeX: {LATEX_PATH}")


if __name__ == "__main__":
    main()
